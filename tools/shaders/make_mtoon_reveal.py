#!/usr/bin/env python3
"""Generates shaders/phoenix/mtoon_reveal.gdshaderinc: the Godot-MToon-Shader common include (MIT, V-Sekai
contributors / Masataka SUMI - addons/Godot-MToon-Shader/LICENSE) with Oriel's transformation reveal injected
(shaders/phoenix/reveal_mask.gdshaderinc): the world position is captured at the start of vertex(), fragments of
garments not yet "made" are discarded at the start of fragment(), and the burning seam is added to EMISSION.
The addon itself is not modified. PhoenixHuman builds its reveal shaders from each material's own MToon variant
code with the include path pointed here (so cull / cutout / transparent / outline variants keep their modes).

  python3 tools/shaders/make_mtoon_reveal.py
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "addons/Godot-MToon-Shader/mtoon_common.gdshaderinc")
DST = os.path.join(ROOT, "shaders/phoenix/mtoon_reveal.gdshaderinc")

s = open(SRC).read()
head = ("// GENERATED by tools/shaders/make_mtoon_reveal.py from addons/Godot-MToon-Shader/mtoon_common.gdshaderinc\n"
        "// (MIT License, Copyright (c) 2020-2022 V-Sekai Contributors, (c) 2018 Masataka SUMI) with Oriel's reveal.\n"
        '#include "res://shaders/phoenix/reveal_mask.gdshaderinc"\n')
assert s.count("void vertex() {") == 1 and s.count("void fragment() {") == 1 and s.count("\tEMISSION = emission;") == 1
s = s.replace("void vertex() {", "void vertex() {\n\trv_wp = (MODEL_MATRIX * vec4(VERTEX, 1.0)).xyz;", 1)
s = s.replace("void fragment() {", "void fragment() {\n\tfloat rv_edge = 0.0;\n\tif (rv_on > 0.5) {\n\t\tif (rv_eval(rv_wp, rv_edge) < 0.0) {\n\t\t\tdiscard;\n\t\t}\n\t}", 1)
s = s.replace("\tEMISSION = emission;", "\tEMISSION = emission + rv_edge_col * rv_edge * 4.0;", 1)
open(DST, "w").write(head + s)
print("wrote", DST)
